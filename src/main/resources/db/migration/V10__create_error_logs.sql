-- FR-ADM-09 에러 로그 관리(02. 관리 ERD의 error_logs, global 모듈 소유)
--   error_logs : 전역 예외 처리기에 도달한 미처리 예외(응답 500)를 기록한다. 업무 예외(CustomException 등 4xx)는 기록하지 않는다.
--                추가·조회만 한다(append-only, 수정·삭제 API 없음). 사용자는 FK 없이 ID 값만 남긴다(로그 보존).
--   저장하지 않는 값: 요청 본문·헤더(Authorization, Cookie)·쿼리 문자열. api_path는 쿼리 문자열을 뺀 경로다.
--   message·stack_trace는 저장 직전에 민감값을 마스킹한다(NFR-06, SensitiveValueMasker). message는 2000자, stack_trace는 서비스에서 길이를 제한한다.
-- 보관 기간(1년, NFR-07) 정리는 구현하지 않는다(삭제 정책·스케줄러 결정 필요, FR-ADM-04 감사 로그 정리와 함께 다룬다).
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE error_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    http_method VARCHAR(10),
    api_path    VARCHAR(300),
    user_id     BIGINT,
    error_type  VARCHAR(200)                NOT NULL,
    message     VARCHAR(2000),
    stack_trace TEXT
);

-- 기간 조회, 1년 초과 기록 정리(이후 구현)
CREATE INDEX idx_error_logs_occurred_at ON error_logs (occurred_at);
-- 유형별 기간 조회
CREATE INDEX idx_error_logs_error_type_occurred_at ON error_logs (error_type, occurred_at);
