-- FR-TSK-01 업무 CRUD(SCRUM-109): 업무 상세 컬럼(04. WBS·일정 ERD의 wbs_tasks 계획 컬럼 일부)과 변경 이력(05. 업무·보드 ERD의 task_histories).
--   wbs_tasks.task_type           : 유형 TASK(작업)·DEFECT(결함). 기본 TASK
--   wbs_tasks.priority            : 우선순위 HIGH·MEDIUM·LOW. 기본 MEDIUM
--   wbs_tasks.completion_criteria : 완료 조건(선택)
--   wbs_tasks.completed_at        : 완료 처리 시각. 상태가 DONE이 되는 시점에 칸반(FR-TSK-02, SCRUM-110)이 기록한다
--   board_column_id·status_changed_at은 FR-TSK-02(V12)에서 추가한다.
--   task_histories                : 업무 생성·배정·일정·상세 변경 등 수행 이력. 추가만 하고 수정·삭제하지 않는다.
-- enum 컬럼: task_type·priority는 값이 닫혀 있어 CHECK를 둔다(00. 개요·규칙 5절).
--   task_histories.activity_type은 FR-TSK-04·06, FR-AIR-14 등이 값을 늘려 가는 코드 enum(TaskActivityType) 기준이라
--   audit_logs.action과 같이 CHECK 없이 둔다(5절 예외).
-- task_histories.task_id는 FK를 두지 않는다(05. 업무·보드 ERD의 fk_task_histories_task와 다름, 결정·미결):
--   이력은 추가만 하는 기록이라 작업을 지울 때 이력 행을 지울 수 없고, FK(NO ACTION)를 두면 이력이 있는 작업은 지울 수 없다.
--   작업 삭제(FR-WBS-01, PM)를 막지 않으면서 이력을 보존하는 쪽으로, 작업이 지워져도 이력 행(삭제 이력 포함)은 남긴다.
--   삭제 정책(00. 개요·규칙 6절)이 정해지면 고아 이력 정리 후 FK를 추가하는 새 버전으로 바꿀 수 있다(되돌리기 쉬운 쪽).
-- before_value·after_value는 ERD대로 JSONB(테스트 DB H2 PostgreSQL 모드도 JSONB를 받는다). 서버가 정한 필드만 넣는다.
-- 기존 데이터 영향: wbs_tasks에 NOT NULL 컬럼 2개를 기본값과 함께 추가하므로 기존 행은 TASK·MEDIUM으로 채워진다(expand).
--   나머지 두 컬럼은 NULL 허용. 기존 작업의 과거 이력은 만들지 않는다(이 버전 이후 변경부터 기록).
-- 되돌릴 때는 task_histories를 지우고 네 컬럼을 삭제하는 새 버전을 추가한다(roll-forward). 컬럼 삭제는 코드 배포 뒤에 한다(contract).

ALTER TABLE wbs_tasks ADD COLUMN task_type VARCHAR(20) NOT NULL DEFAULT 'TASK';
ALTER TABLE wbs_tasks ADD COLUMN priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM';
ALTER TABLE wbs_tasks ADD COLUMN completion_criteria VARCHAR(2000);
ALTER TABLE wbs_tasks ADD COLUMN completed_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE wbs_tasks ADD CONSTRAINT ck_wbs_tasks_task_type CHECK (task_type IN ('TASK', 'DEFECT'));
ALTER TABLE wbs_tasks ADD CONSTRAINT ck_wbs_tasks_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW'));

CREATE TABLE task_histories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT                      NOT NULL,
    activity_type VARCHAR(30)                 NOT NULL,
    before_value  JSONB,
    after_value   JSONB,
    actor_user_id BIGINT,
    occurred_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_histories_actor_user FOREIGN KEY (actor_user_id) REFERENCES users (id)
);

-- 업무별 이력 타임라인(커서, id 순)
CREATE INDEX idx_task_histories_task_id_id ON task_histories (task_id, id);
