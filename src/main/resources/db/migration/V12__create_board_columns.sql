--   board_columns.name            : 컬럼 이름(사용자 입력, 최대 50자). NULL이면 기본 이름 — 표시 문구는 공통 코드 라벨
--                                   code.TASK_STATUS.<status_category>를 다국어로 보여 준다(FR-ADM-06·07, ERD 결정: NULL 허용으로 변경)
--   board_columns.status_category : 이 컬럼으로 옮긴 카드가 갖는 상태(TASK_STATUS 코드 TODO·IN_PROGRESS·REVIEW·DONE). 만든 뒤 바꾸지 않는다
--   board_columns.sort_order      : 보드 안 표시 순서(1부터, 삭제 후 빈 번호 허용, 정렬은 sort_order·id)
--   board_columns.wip_limit       : WIP 한도. NULL이면 없음. 넘으면 경고만 한다(차단 아님, FR-TSK-02 인수 기준)
--   wbs_tasks.board_column_id     : 카드가 놓인 컬럼. 상태는 컬럼의 status_category와 같게 유지한다
--   wbs_tasks.status_changed_at   : 마지막 상태 변경 시각(FR-AIR-02 상태 체류). NULL이면 등록 이후 상태가 바뀐 적 없음(체류 기준 = created_at)
-- enum 컬럼: status_category는 TASK_STATUS 코드(V8 시드)와 같은 닫힌 값이라 CHECK를 둔다(00. 개요·규칙 5절).
--   새 상태 코드를 추가하면 이 CHECK와 WbsTaskStatus·CodeSeedConsistencyTest를 같은 버전에서 함께 바꾼다.
-- 기존 데이터 영향(백필):
--   1) 모든 기존 프로젝트에 기본 컬럼 4개(대기·진행·검토·완료 = TODO·IN_PROGRESS·REVIEW·DONE, 이름 NULL, WIP 없음)를 만든다.
--      기능 모듈(KANBAN) 사용 여부와 관계없이 만든다(FR-PRJ-06: 다시 켜면 기존 데이터 그대로 표시).
--   2) 기존 작업은 자기 status와 같은 기본 컬럼으로 board_column_id를 채운다. V12 이전에는 상태 변경 API가 없어 모두 TODO다.
--   3) status_changed_at은 채우지 않는다(NULL = 등록 이후 변경 없음).
--   프로젝트·작업 수에 비례하는 INSERT 1회(4문)·UPDATE 1회이며 잠금은 이 마이그레이션 동안만 잡힌다.
-- 되돌릴 때는 fk·컬럼을 지우고 board_columns를 지우는 새 버전을 추가한다(roll-forward). 컬럼 삭제는 코드 배포 뒤에 한다(contract).

CREATE TABLE board_columns (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT                      NOT NULL,
    name            VARCHAR(50),
    status_category VARCHAR(20)                 NOT NULL,
    sort_order      INT                         NOT NULL,
    wip_limit       INT,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_board_columns_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_board_columns_status_category CHECK (status_category IN ('TODO', 'IN_PROGRESS', 'REVIEW', 'DONE')),
    CONSTRAINT ck_board_columns_name CHECK (name IS NULL OR LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_board_columns_sort_order CHECK (sort_order > 0),
    CONSTRAINT ck_board_columns_wip_limit CHECK (wip_limit IS NULL OR wip_limit > 0)
);

-- 프로젝트 보드 컬럼 조회
CREATE INDEX idx_board_columns_project_id ON board_columns (project_id);

ALTER TABLE wbs_tasks ADD COLUMN board_column_id BIGINT;
ALTER TABLE wbs_tasks ADD COLUMN status_changed_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE wbs_tasks ADD CONSTRAINT fk_wbs_tasks_board_column FOREIGN KEY (board_column_id) REFERENCES board_columns (id);

-- 컬럼 삭제 시 카드 유무 확인·FK 검사용
CREATE INDEX idx_wbs_tasks_board_column_id ON wbs_tasks (board_column_id);

