-- request_id + request_hash preserve creation idempotency even after title/due-date edits.
CREATE TABLE personal_todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    due_date DATE,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    done_at TIMESTAMP(6) WITH TIME ZONE,
    request_id VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_personal_todos_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_personal_todos_user_id_request_id UNIQUE (user_id, request_id),
    CONSTRAINT ck_personal_todos_done_at CHECK ((done = FALSE AND done_at IS NULL) OR (done = TRUE AND done_at IS NOT NULL))
);
CREATE INDEX idx_personal_todos_user_id_due_date ON personal_todos (user_id, due_date);
