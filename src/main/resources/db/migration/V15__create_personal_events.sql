-- Expand only: a new table; existing tables and the V13/V14 personal_todos flow are unchanged.
-- Rollback: disable the /api/me/events API, export personal data, then roll forward with a new migration.
-- Do not drop this table automatically. Retention and purge policy for personal items is not decided.
-- start_at < end_at is enforced in the DB as well as in SchedulePolicy.
CREATE TABLE personal_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    start_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    all_day BOOLEAN NOT NULL DEFAULT FALSE,
    memo VARCHAR(2000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_personal_events_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_personal_events_period CHECK (start_at < end_at)
);
CREATE INDEX idx_personal_events_user_id_start_at ON personal_events (user_id, start_at);
