-- Expand only. Keep legacy private daily content private; PMs read task-specific content only.
CREATE TABLE worklog_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 worklog_id BIGINT NOT NULL REFERENCES worklogs(id),
 task_id BIGINT NOT NULL REFERENCES wbs_tasks(id),
 content TEXT,
 progress INTEGER NOT NULL CHECK (progress BETWEEN 0 AND 100),
 spent_minutes INTEGER NOT NULL CHECK (spent_minutes BETWEEN 0 AND 1440),
 completed BOOLEAN NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_worklog_tasks_log_task UNIQUE(worklog_id, task_id),
 CONSTRAINT ck_worklog_tasks_completed CHECK (NOT completed OR progress = 100)
);
CREATE INDEX idx_worklog_tasks_task ON worklog_tasks(task_id);
CREATE INDEX idx_wbs_tasks_assignee_dates ON wbs_tasks(assignee_user_id, start_date, end_date, id);
