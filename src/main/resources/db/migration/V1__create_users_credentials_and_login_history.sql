-- FR-ADM-01 로그인·계정
--   users             : 사람·조직 정보. 인증 방식(로컬/사내 SSO)과 무관하게 유지된다 (global.user)
--   local_credentials : 로컬 ID/PW 로그인 정보. SSO 전환 시 이 테이블만 제거한다 (authserver)
--   login_history     : 로그인 시도 기록 (append-only, 조회는 FR-ADM-04)
-- 시각은 모두 UTC instant(timestamptz)로 저장한다. 표시 시간대 변환은 응답·화면 경계에서 한다.
-- 신규 테이블만 만드는 마이그레이션이라 기존 데이터 영향은 없다. 되돌릴 때는 삭제용 새 버전을 추가한다(roll-forward).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id      VARCHAR(50)                 NOT NULL,
    name          VARCHAR(50)                 NOT NULL,
    system_role   VARCHAR(30)                 NOT NULL,
    status        VARCHAR(20)                 NOT NULL,
    last_login_at TIMESTAMP(6) WITH TIME ZONE,
    version       BIGINT                      NOT NULL DEFAULT 0,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_login_id UNIQUE (login_id),
    CONSTRAINT ck_users_system_role CHECK (system_role IN ('SYSTEM_ADMIN', 'EXECUTIVE', 'USER')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE local_credentials (
    user_id              BIGINT                      NOT NULL PRIMARY KEY,
    password_hash        VARCHAR(255)                NOT NULL,
    failed_login_count   INTEGER                     NOT NULL DEFAULT 0,
    locked_at            TIMESTAMP(6) WITH TIME ZONE,
    must_change_password BOOLEAN                     NOT NULL DEFAULT TRUE,
    password_changed_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version              BIGINT                      NOT NULL DEFAULT 0,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_local_credentials_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_local_credentials_failed_login_count CHECK (failed_login_count >= 0)
);

CREATE TABLE login_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT,
    login_id       VARCHAR(50)                 NOT NULL,
    result         VARCHAR(20)                 NOT NULL,
    failure_reason VARCHAR(30),
    ip_address     VARCHAR(45)                 NOT NULL,
    occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_login_history_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_login_history_result CHECK (result IN ('SUCCESS', 'FAILURE'))
);

-- FR-ADM-04 조회 조건(기간·사용자)용
CREATE INDEX idx_login_history_occurred_at ON login_history (occurred_at);
CREATE INDEX idx_login_history_user_id_occurred_at ON login_history (user_id, occurred_at);
