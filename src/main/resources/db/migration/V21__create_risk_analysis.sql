-- 리스크 일일 계산 실행·감지 결과(10. AI 리스크·AI 초안 ERD).
-- FR-AIR-01(일정 지연 감지, SCRUM-127)이 처음 쓰고, FR-AIR-02·03·누락 탐지가 같은 테이블에
-- detection_type·reason_code만 달리해 쓴다. 점수·대응 테이블(project_risk_scores·risk_responses)은 후속.
--   하루 1회 실행(uk_risk_analysis_runs_run_date). 계산에 쓴 임계값은 settings_snapshot에 남긴다.
--   감지 행은 추가만 하고 수정·삭제하지 않는다(삭제 정책 미정, 00. 개요·규칙 6절).
-- enum 컬럼: status·detection_type·reason_code·target_type은 값이 닫혀 있어 CHECK를 둔다.
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE risk_analysis_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date           DATE                         NOT NULL,
    status             VARCHAR(20)                  NOT NULL,
    started_at         TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    finished_at        TIMESTAMP(6) WITH TIME ZONE,
    settings_snapshot  JSONB                        NOT NULL,
    CONSTRAINT uk_risk_analysis_runs_run_date UNIQUE (run_date),
    CONSTRAINT ck_risk_analysis_runs_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE TABLE risk_detections (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT         NOT NULL,
    project_id      BIGINT         NOT NULL,
    detection_type  VARCHAR(20)    NOT NULL,
    reason_code     VARCHAR(50)    NOT NULL,
    target_type     VARCHAR(30)    NOT NULL,
    target_id       BIGINT         NOT NULL,
    metric_value    NUMERIC(10, 2),
    impact_days     INT,
    details         JSONB,
    CONSTRAINT fk_risk_detections_run FOREIGN KEY (run_id) REFERENCES risk_analysis_runs (id),
    CONSTRAINT fk_risk_detections_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_risk_detections_type CHECK (detection_type IN ('DELAY', 'BOTTLENECK', 'OVERLOAD', 'MISSING')),
    CONSTRAINT ck_risk_detections_reason CHECK (reason_code IN (
        'OVERDUE', 'PROGRESS_BEHIND', 'PREDECESSOR_DELAY', 'MILESTONE_AT_RISK',
        'STATUS_STAY', 'APPROVAL_WAIT', 'ISSUE_REOPEN',
        'OVER_ALLOCATION',
        'NO_ASSIGNEE', 'NO_ACTIVITY', 'ACTION_ITEM_UNREGISTERED')),
    CONSTRAINT ck_risk_detections_target CHECK (target_type IN (
        'TASK', 'MILESTONE', 'DELIVERABLE', 'ISSUE', 'USER', 'ACTION_ITEM'))
);

CREATE INDEX idx_risk_detections_run_id_project_id ON risk_detections (run_id, project_id);
CREATE INDEX idx_risk_detections_target_type_target_id ON risk_detections (target_type, target_id);
