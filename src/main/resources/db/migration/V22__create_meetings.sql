-- Expand only: 신규 테이블만 추가한다. rollback은 API를 비활성화한 뒤 새 migration으로 테이블을 제거한다.
CREATE TABLE meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    held_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    content TEXT,
    author_user_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_meetings_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_meetings_author_user FOREIGN KEY (author_user_id) REFERENCES users (id)
);

CREATE TABLE meeting_attendees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    user_id BIGINT,
    external_name VARCHAR(50),
    CONSTRAINT fk_meeting_attendees_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id),
    CONSTRAINT fk_meeting_attendees_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_meeting_attendees_identity CHECK (
        (user_id IS NOT NULL AND external_name IS NULL)
        OR (user_id IS NULL AND external_name IS NOT NULL)
    )
);

CREATE TABLE meeting_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    content VARCHAR(1000) NOT NULL,
    sort_order INT NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_meeting_decisions_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id),
    CONSTRAINT ck_meeting_decisions_source CHECK (source IN ('MANUAL', 'AI')),
    CONSTRAINT ck_meeting_decisions_sort_order CHECK (sort_order >= 0)
);

CREATE TABLE action_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    content VARCHAR(1000) NOT NULL,
    assignee_user_id BIGINT,
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    task_id BIGINT,
    approved_by BIGINT,
    approved_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_action_items_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id),
    CONSTRAINT fk_action_items_assignee_user FOREIGN KEY (assignee_user_id) REFERENCES users (id),
    CONSTRAINT fk_action_items_task FOREIGN KEY (task_id) REFERENCES wbs_tasks (id),
    CONSTRAINT fk_action_items_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT ck_action_items_status CHECK (status IN ('OPEN', 'CONVERTED', 'DISMISSED')),
    CONSTRAINT ck_action_items_source CHECK (source IN ('MANUAL', 'AI'))
);

CREATE INDEX idx_meetings_project_id_held_at ON meetings (project_id, held_at);
CREATE INDEX idx_meeting_attendees_meeting_id ON meeting_attendees (meeting_id);
CREATE INDEX idx_meeting_decisions_meeting_id ON meeting_decisions (meeting_id);
CREATE INDEX idx_action_items_meeting_id ON action_items (meeting_id);
CREATE INDEX idx_action_items_status_task_id ON action_items (status, task_id);
