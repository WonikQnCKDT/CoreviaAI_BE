-- 회의록 생성 멱등 키. V22 이후 적용하며 기존 회의록은 키 없이 유지한다.
-- 구 API와 혼용하면 구 API는 중복을 막지 못하므로 신 API로 전환한 뒤 구 API를 종료한다.
-- Rollback: 신 API를 중지하고 키를 보존한 채 호환 버전을 배포한다. 테이블 제거는 별도 roll-forward다.
CREATE TABLE meeting_create_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    author_user_id BIGINT NOT NULL REFERENCES users(id),
    request_id VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    meeting_id BIGINT REFERENCES meetings(id),
    CONSTRAINT uk_meeting_create_request UNIQUE (project_id, author_user_id, request_id),
    CONSTRAINT uk_meeting_create_request_meeting UNIQUE (meeting_id)
);
