CREATE TABLE menus (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id     BIGINT,
    menu_key      VARCHAR(50)                 NOT NULL,
    label_key     VARCHAR(100)                NOT NULL,
    url_path      VARCHAR(200),
    sort_order    INT                         NOT NULL,
    required_role VARCHAR(30),
    active        BOOLEAN                     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_menus_menu_key UNIQUE (menu_key),
    CONSTRAINT fk_menus_parent FOREIGN KEY (parent_id) REFERENCES menus (id),
    CONSTRAINT ck_menus_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_menus_required_role CHECK (
        required_role IS NULL OR required_role IN ('SYSTEM_ADMIN', 'EXECUTIVE', 'USER'))
);

CREATE INDEX idx_menus_parent_id ON menus (parent_id);

