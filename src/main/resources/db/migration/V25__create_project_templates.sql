-- FR-PRJ-09 프로젝트 템플릿. 생성 화면의 기본값만 저장하고, 프로젝트는 생성 시점에 그 값을 복사한다.
-- 템플릿을 고쳐도 이미 만든 프로젝트의 단계·액터·기능은 바뀌지 않는다.
-- default_config는 서버가 검증한 JSON 텍스트다(phases, actors, features, requiredDeliverables).
-- JSONB로 두면 문자 컬럼과 겹쳐 값이 한 번 더 감싸이므로 VARCHAR로 저장한다.
-- 필수 산출물 행을 만드는 도메인은 아직 없으므로 이름 목록만 보관하고, 생성 시 산출물 테이블에는 쓰지 않는다.
-- 되돌릴 때는 이 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE project_templates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_key    VARCHAR(50)                 NOT NULL,
    name            VARCHAR(100)                NOT NULL,
    methodology     VARCHAR(20)                 NOT NULL,
    department_type VARCHAR(20),
    default_config  VARCHAR(4000)               NOT NULL,
    status          VARCHAR(20)                 NOT NULL,
    version         BIGINT                      NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_project_templates_template_key UNIQUE (template_key)
);

