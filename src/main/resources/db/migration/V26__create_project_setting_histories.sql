-- FR-PRJ-14 프로젝트 설정 변경 이력. 추가만 하는 기록이라 수정·삭제하지 않는다.
-- before_value·after_value는 서버가 정한 필드의 JSON이다(업무 이력과 같이 JSONB).
-- 되돌릴 때는 이 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE project_setting_histories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT                      NOT NULL,
    change_type  VARCHAR(30)                 NOT NULL,
    before_value JSONB,
    after_value  JSONB,
    changed_by   BIGINT                      NOT NULL,
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_setting_histories_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_project_setting_histories_changed_by FOREIGN KEY (changed_by) REFERENCES users (id)
);

CREATE INDEX idx_project_setting_histories_project_id_id ON project_setting_histories (project_id, id);
