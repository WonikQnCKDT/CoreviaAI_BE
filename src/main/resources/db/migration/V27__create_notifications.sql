-- FR-NTF-01 인앱 알림 (12. 알림 ERD의 notifications)
--   수신자별 알림. 미확인은 read_at NULL. 문구는 라벨 키와 파라미터만 저장한다.
--   발생 이력은 지우거나 본문을 고치지 않는다. 확인 처리만 read_at을 채운다.
--   멘션·승인 요청·누락·리스크 등급·미활동 프로젝트는 그 이벤트를 만드는 기능이 생길 때 같은 표에 쌓는다.
-- 기존 데이터 영향: 새 테이블만 만든다.
-- 되돌릴 때는 이 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE notifications (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id  BIGINT                      NOT NULL,
    notification_type  VARCHAR(30)                 NOT NULL,
    project_id         BIGINT,
    target_type        VARCHAR(30),
    target_id          BIGINT,
    message_key        VARCHAR(100)                NOT NULL,
    message_params     JSONB,
    channel            VARCHAR(20)                 NOT NULL DEFAULT 'IN_APP',
    read_at            TIMESTAMP(6) WITH TIME ZONE,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_recipient_user FOREIGN KEY (recipient_user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_notifications_type CHECK (notification_type IN (
        'ASSIGNED', 'MENTIONED', 'STATUS_CHANGED', 'DUE_SOON',
        'APPROVAL_REQUESTED', 'MISSING_TASK', 'RISK_UP', 'PROJECT_INACTIVE'
    )),
    CONSTRAINT ck_notifications_channel CHECK (channel IN ('IN_APP'))
);

CREATE INDEX idx_notifications_recipient_user_id_read_at_id
    ON notifications (recipient_user_id, read_at, id);
CREATE INDEX idx_notifications_created_at ON notifications (created_at);
