-- FR-ADM-10 계정 신청·승인 (02. 관리 ERD의 account_requests)
--   신청 → 승인/반려. 승인 시 users 행을 만들고 user_id로 연결한다. 비밀번호는 이 테이블에 두지 않는다.
--   대기 중인 같은 login_id는 pending_login_id 유니크로 한 건만 허용한다. 승인·반려 때 그 값을 비워 재신청할 수 있다.
--   이력은 수정·삭제하지 않고 상태 전이와 audit_logs로만 남긴다.
-- 기존 데이터 영향: 새 테이블만 만든다.
-- 되돌릴 때는 이 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE account_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id         VARCHAR(50)                 NOT NULL,
    name             VARCHAR(50)                 NOT NULL,
    department_id    BIGINT,
    purpose          VARCHAR(500)                NOT NULL,
    status           VARCHAR(20)                 NOT NULL DEFAULT 'PENDING',
    reject_reason    VARCHAR(500),
    reviewed_by      BIGINT,
    reviewed_at      TIMESTAMP(6) WITH TIME ZONE,
    user_id          BIGINT,
    -- 대기 중 login_id. 승인·반려 시 NULL. UNIQUE는 NULL을 서로 다르게 봐서 재신청이 가능하다.
    -- 부분 유니크 인덱스는 H2가 지원하지 않아 컬럼으로 둔다. 응답·ERD 업무 컬럼이 아니다.
    pending_login_id VARCHAR(50),
    version          BIGINT                      NOT NULL DEFAULT 0,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_account_requests_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_account_requests_reviewed_by FOREIGN KEY (reviewed_by) REFERENCES users (id),
    CONSTRAINT fk_account_requests_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_account_requests_pending_login_id UNIQUE (pending_login_id),
    CONSTRAINT ck_account_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_account_requests_reject_reason CHECK (
        (status = 'REJECTED' AND reject_reason IS NOT NULL)
            OR (status <> 'REJECTED' AND reject_reason IS NULL)
    ),
    CONSTRAINT ck_account_requests_review CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND user_id IS NULL)
            OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT ck_account_requests_approved_user CHECK (
        (status = 'APPROVED' AND user_id IS NOT NULL) OR (status <> 'APPROVED' AND user_id IS NULL)
    )
);

-- 대기 목록·상태 필터
CREATE INDEX idx_account_requests_status_created_at ON account_requests (status, created_at);
-- 신청자 상태 조회(login_id + name)
CREATE INDEX idx_account_requests_login_id ON account_requests (login_id);
