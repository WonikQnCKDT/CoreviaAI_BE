-- FR-ADM-02 사용자·조직 관리
--   departments : 부서(조직). parent_id로 상위·하위 계층을 표현한다. 삭제하지 않고 status=INACTIVE로 비활성화한다 (global.department)
--   users       : 소속 부서(1인 1부서), 직무, 프로젝트 생성 권한 컬럼 추가 (global.user)
--   audit_logs  : 감사 로그(권한·계정·조직 변경 등). append-only, 조회 화면·1년 보관 정리는 FR-ADM-04 (global.audit)
-- 기존 데이터 영향: users에 NULL 허용 컬럼과 기본값(false)이 있는 컬럼만 추가하므로 기존 행은 그대로 유효하다.
-- 되돌릴 때는 추가한 컬럼·테이블을 삭제하는 새 버전을 추가한다(roll-forward).

CREATE TABLE departments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT,
    name       VARCHAR(50)                 NOT NULL,
    status     VARCHAR(20)                 NOT NULL,
    version    BIGINT                      NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_departments_parent FOREIGN KEY (parent_id) REFERENCES departments (id),
    -- 같은 상위 부서 안에서만 이름 중복 금지. 최상위(parent_id NULL)끼리는 UNIQUE가 NULL을 서로 다르게 보므로 서비스에서 검사한다.
    CONSTRAINT uk_departments_parent_id_name UNIQUE (parent_id, name),
    CONSTRAINT ck_departments_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_departments_parent_id ON departments (parent_id);

-- 시스템 관리자는 부서가 없을 수 있어 NULL 허용. 그 외 역할의 부서 필수 여부는 API에서 검증한다.
ALTER TABLE users ADD COLUMN department_id BIGINT;
ALTER TABLE users ADD COLUMN job_title VARCHAR(50);
ALTER TABLE users ADD COLUMN can_create_project BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD CONSTRAINT fk_users_department FOREIGN KEY (department_id) REFERENCES departments (id);

CREATE INDEX idx_users_department_id ON users (department_id);

-- target_id는 대상 종류(target_type)마다 다른 테이블을 가리키므로 FK를 두지 않는다.
-- actor_user_id도 로그 보존을 위해 FK 없이 값만 남긴다(사용자는 삭제하지 않고 비활성화한다).
-- action 값은 코드 enum(AuditAction) 기준이며, 값 추가 시 마이그레이션이 필요 없도록 CHECK 제약을 두지 않는다.
-- details는 변경 전·후 값 JSON 문자열. 테스트 DB(H2)와 함께 쓰기 위해 JSONB 대신 VARCHAR로 저장한다.
CREATE TABLE audit_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    action        VARCHAR(50)                 NOT NULL,
    target_type   VARCHAR(30)                 NOT NULL,
    target_id     BIGINT,
    details       VARCHAR(4000),
    ip_address    VARCHAR(45),
    occurred_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- FR-ADM-04 조회 조건(기간·대상·행위자)용
CREATE INDEX idx_audit_logs_occurred_at ON audit_logs (occurred_at);
CREATE INDEX idx_audit_logs_target_type_target_id_occurred_at ON audit_logs (target_type, target_id, occurred_at);
CREATE INDEX idx_audit_logs_actor_user_id_occurred_at ON audit_logs (actor_user_id, occurred_at);
