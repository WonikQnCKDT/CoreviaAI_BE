-- FR-PRJ-01 프로젝트 생성(운영 방식·액터 지정 포함)
--   projects        : 프로젝트. pm_user_id는 현재 PM(위임으로 바뀜, FR-PRJ-04), created_by는 최초 생성자로 분리한다
--   project_actors  : 생성 시 지정한 액터. 여기 있는 액터만 멤버 역할로 선택할 수 있다
--   project_members : 멤버와 역할. 한 사람은 한 프로젝트에서 역할 하나만 갖는다
--   project_phases  : 폭포수 5단계와 게이트. 게이트 승인자는 미지정(NULL)일 수 있고, 계획·실제 일자 컬럼은 FR-PRJ-05에서 추가한다
-- enum 값(visibility·methodology·status 등)은 코드 기준이며, 값 추가 시 마이그레이션이 필요 없도록 CHECK 제약을 두지 않는다(audit_logs.action과 같은 방식).
-- 기간(start_date·end_date)은 달력 의미를 갖는 날짜라 DATE로 저장한다(UTC 시각 아님).
-- 되돌릴 때는 추가한 테이블을 삭제하는 새 버전을 추가한다(roll-forward).

CREATE TABLE projects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)                 NOT NULL,
    name            VARCHAR(100)                NOT NULL,
    start_date      DATE                        NOT NULL,
    end_date        DATE                        NOT NULL,
    department_id   BIGINT                      NOT NULL,
    visibility      VARCHAR(20)                 NOT NULL,
    methodology     VARCHAR(20)                 NOT NULL,
    department_type VARCHAR(20)                 NOT NULL,
    status          VARCHAR(20)                 NOT NULL,
    pm_user_id      BIGINT                      NOT NULL,
    created_by      BIGINT                      NOT NULL,
    version         BIGINT                      NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_projects_code UNIQUE (code),
    CONSTRAINT fk_projects_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_projects_pm_user FOREIGN KEY (pm_user_id) REFERENCES users (id),
    CONSTRAINT fk_projects_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);

-- FR-PRJ-01 목록 필터(상태·주관 부서·PM)용
CREATE INDEX idx_projects_status ON projects (status);
CREATE INDEX idx_projects_department_id ON projects (department_id);
CREATE INDEX idx_projects_pm_user_id ON projects (pm_user_id);

CREATE TABLE project_actors (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT                      NOT NULL,
    actor      VARCHAR(30)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_actors_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT uk_project_actors_project_id_actor UNIQUE (project_id, actor)
);

CREATE TABLE project_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT                      NOT NULL,
    user_id    BIGINT                      NOT NULL,
    actor      VARCHAR(30)                 NOT NULL,
    version    BIGINT                      NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_members_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_project_members_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_project_members_project_id_user_id UNIQUE (project_id, user_id)
);

-- 공개 범위 판정(멤버 여부)과 내 프로젝트 조회용
CREATE INDEX idx_project_members_user_id ON project_members (user_id);

CREATE TABLE project_phases (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id            BIGINT                      NOT NULL,
    phase_type            VARCHAR(20)                 NOT NULL,
    phase_order           INT                         NOT NULL,
    status                VARCHAR(20)                 NOT NULL,
    gate_status           VARCHAR(20)                 NOT NULL,
    gate_approver_user_id BIGINT,
    version               BIGINT                      NOT NULL DEFAULT 0,
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_phases_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_project_phases_gate_approver FOREIGN KEY (gate_approver_user_id) REFERENCES users (id),
    CONSTRAINT uk_project_phases_project_id_phase_order UNIQUE (project_id, phase_order)
);
