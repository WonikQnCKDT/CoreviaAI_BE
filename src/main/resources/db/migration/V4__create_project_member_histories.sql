-- FR-PRJ-04 멤버·역할 관리
--   project_member_histories : 멤버 초대·역할 변경·제외와 PM 위임·재지정 이력. 추가만 하고 수정·삭제하지 않는다.
--     감사 로그(audit_logs)는 1년 보관 후 정리하는 운영 기록이라, 프로젝트와 함께 남아야 하는 업무 이력은 따로 둔다.
--     한 행은 사람 한 명의 역할 변화 한 건이다. 초대는 before_actor가 NULL, 제외는 after_actor가 NULL이고,
--     PM 위임·재지정은 신규 PM과 기존 PM 두 행을 같은 change_type으로 남긴다.
-- change_type은 FR-PRJ-04 안에서 닫힌 값이라 CHECK 제약을 둔다(값 추가 시 이 제약도 새 버전에서 수정).
-- before_actor·after_actor는 project_members.actor와 같은 값이라 V3와 같이 CHECK 없이 저장한다.
-- 기존 데이터 영향: 새 테이블만 추가한다. FR-PRJ-01 생성 시 초대한 멤버는 이력 없이 시작한다(생성 감사 로그에 남아 있음).
-- 되돌릴 때는 이 테이블을 삭제하는 새 버전을 추가한다(roll-forward).

CREATE TABLE project_member_histories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT                      NOT NULL,
    user_id      BIGINT                      NOT NULL,
    change_type  VARCHAR(20)                 NOT NULL,
    before_actor VARCHAR(30),
    after_actor  VARCHAR(30),
    changed_by   BIGINT                      NOT NULL,
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_member_histories_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_project_member_histories_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_project_member_histories_changed_by FOREIGN KEY (changed_by) REFERENCES users (id),
    CONSTRAINT ck_project_member_histories_change_type
        CHECK (change_type IN ('INVITED', 'ROLE_CHANGED', 'REMOVED', 'PM_DELEGATED', 'PM_REASSIGNED'))
);

-- 프로젝트별 이력 커서 조회(id 내림차순)용
CREATE INDEX idx_project_member_histories_project_id_id ON project_member_histories (project_id, id);
