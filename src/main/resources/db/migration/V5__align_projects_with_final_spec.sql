-- 요구사항명세 최종안(전사관리) 반영: FR-PRJ-01·04·06·09, 3.1(프로젝트 생성 권한 개방)
--   1) 프로젝트 생성 권한 제한 폐지: users.can_create_project 삭제(일반 사용자 전원 생성 가능)
--   2) 기간 후입력: projects.start_date·end_date NULL 허용
--   3) 주관 부서 0~N개: project_departments 신설, projects.department_id 이관 후 삭제
--   4) 복수 PM: PM은 project_members.actor = 'PM'으로만 관리하고 projects.pm_user_id 삭제
--   5) 템플릿(빈/IT 프로젝트)·운영 방식 '단계 없음'(NONE): projects.template 추가
--   6) 기능 구성(FR-PRJ-06): project_features 신설
--   7) 멤버 이력에 PM 추가·해제(PM_ADDED·PM_RELEASED) 허용. 기존 PM_DELEGATED 행은 조회용으로 남긴다
-- 기존 데이터 영향: 지금까지 만든 프로젝트는 모두 폭포수라 template = IT_PROJECT, IT 템플릿 기본 기능 모듈을 켠 상태로 이관한다.
--   주관 부서는 기존 department_id 1건으로, PM은 이미 actor = PM 멤버 행이 있어 그대로 유지된다.
-- 배포 순서: 이 마이그레이션과 같은 버전의 애플리케이션을 함께 배포한다(이전 버전 애플리케이션은 삭제된 컬럼을 읽는다).
-- 되돌릴 때는 삭제한 컬럼을 다시 추가하고 project_departments·project_members에서 값을 채우는 새 버전을 추가한다(roll-forward).
--   can_create_project 값은 복원 대상이 아니다(권한 개념 자체를 폐지).

ALTER TABLE users DROP COLUMN can_create_project;

ALTER TABLE projects ALTER COLUMN start_date DROP NOT NULL;
ALTER TABLE projects ALTER COLUMN end_date DROP NOT NULL;

ALTER TABLE projects ADD COLUMN template VARCHAR(20);
UPDATE projects SET template = 'IT_PROJECT';
ALTER TABLE projects ALTER COLUMN template SET NOT NULL;

CREATE TABLE project_departments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT                      NOT NULL,
    department_id BIGINT                      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_departments_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_project_departments_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT uk_project_departments_project_id_department_id UNIQUE (project_id, department_id)
);

-- 목록의 주관 부서 필터와 부서 공개·경영진 소속 범위 판정용
CREATE INDEX idx_project_departments_department_id ON project_departments (department_id);

INSERT INTO project_departments (project_id, department_id, created_at, updated_at)
SELECT id, department_id, created_at, updated_at FROM projects;

ALTER TABLE projects DROP CONSTRAINT fk_projects_department;
DROP INDEX idx_projects_department_id;
ALTER TABLE projects DROP COLUMN department_id;

ALTER TABLE projects DROP CONSTRAINT fk_projects_pm_user;
DROP INDEX idx_projects_pm_user_id;
ALTER TABLE projects DROP COLUMN pm_user_id;

-- PM 판정(프로젝트의 PM 목록, PM 필터)용
CREATE INDEX idx_project_members_project_id_actor ON project_members (project_id, actor);

CREATE TABLE project_features (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT                      NOT NULL,
    feature    VARCHAR(30)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_features_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT uk_project_features_project_id_feature UNIQUE (project_id, feature)
);

