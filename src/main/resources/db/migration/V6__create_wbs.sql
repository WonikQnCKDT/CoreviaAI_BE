-- WBS 기본 테이블(04. WBS·일정 ERD). FR-PRJ-07(AI 초안 반영)이 처음 쓰고, FR-WBS-01·03·04, FR-TSK-01이 이어서 확장한다.
--   wbs_tasks        : 작업(parent_task_id NULL)과 하위작업(parent_task_id = 상위 작업)
--                      단계(project_phases)와의 연결은 두지 않는다(운영 방식 '단계 없음' 도입, ERD 결정 5)
--   wbs_dependencies : 작업 간 완료→시작(FS) 관계. 순환 등록은 서비스에서 막는다(FR-WBS-03)
--   milestones       : 마일스톤. 목표일은 달력 날짜라 DATE
--   milestone_tasks  : 마일스톤에 연결한 작업(FR-WBS-04 지연 경고 기준)
-- enum 컬럼: source·dependency_type은 값이 닫혀 있어 CHECK를 둔다(00. 개요·규칙 5절).
--   wbs_tasks.status는 공통 코드 TASK_STATUS(FR-ADM-07)·칸반 사용자 정의 컬럼(FR-TSK-02)으로 값이 늘 수 있어 CHECK 없이 둔다.
-- ERD의 업무 상세 계획 컬럼(task_type·priority·completion_criteria·board_column_id·status_changed_at·completed_at)은
--   해당 기능(FR-TSK-01·02, FR-AIR-02)에서 추가한다(expand).
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 네 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE wbs_tasks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT                      NOT NULL,
    parent_task_id   BIGINT,
    sort_order       INT                         NOT NULL,
    name             VARCHAR(200)                NOT NULL,
    description      VARCHAR(2000),
    assignee_user_id BIGINT,
    start_date       DATE                        NOT NULL,
    end_date         DATE                        NOT NULL,
    estimated_effort NUMERIC(6, 1),
    progress         INT                         NOT NULL DEFAULT 0,
    status           VARCHAR(20)                 NOT NULL,
    source           VARCHAR(20)                 NOT NULL,
    created_by       BIGINT                      NOT NULL,
    version          BIGINT                      NOT NULL DEFAULT 0,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_wbs_tasks_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_wbs_tasks_parent_task FOREIGN KEY (parent_task_id) REFERENCES wbs_tasks (id),
    CONSTRAINT fk_wbs_tasks_assignee_user FOREIGN KEY (assignee_user_id) REFERENCES users (id),
    CONSTRAINT fk_wbs_tasks_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_wbs_tasks_source CHECK (source IN ('MANUAL', 'AI_DRAFT', 'ACTION_ITEM'))
);

-- 프로젝트별 트리 조회, 하위작업 조회, 담당자별 업무(내 TODO·칸반)
CREATE INDEX idx_wbs_tasks_project_id ON wbs_tasks (project_id);
CREATE INDEX idx_wbs_tasks_parent_task_id ON wbs_tasks (parent_task_id);
CREATE INDEX idx_wbs_tasks_assignee_user_id ON wbs_tasks (assignee_user_id);

CREATE TABLE wbs_dependencies (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          BIGINT                      NOT NULL,
    predecessor_task_id BIGINT                      NOT NULL,
    successor_task_id   BIGINT                      NOT NULL,
    dependency_type     VARCHAR(30)                 NOT NULL,
    created_by          BIGINT                      NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_wbs_dependencies_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_wbs_dependencies_predecessor_task FOREIGN KEY (predecessor_task_id) REFERENCES wbs_tasks (id),
    CONSTRAINT fk_wbs_dependencies_successor_task FOREIGN KEY (successor_task_id) REFERENCES wbs_tasks (id),
    CONSTRAINT fk_wbs_dependencies_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT uk_wbs_dependencies_predecessor_successor UNIQUE (predecessor_task_id, successor_task_id),
    CONSTRAINT ck_wbs_dependencies_dependency_type CHECK (dependency_type IN ('FINISH_TO_START'))
);

-- 후행에서 선행을 거슬러 찾는 파급효과 분석(FR-AIR-04)용
CREATE INDEX idx_wbs_dependencies_successor_task_id ON wbs_dependencies (successor_task_id);

CREATE TABLE milestones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT                      NOT NULL,
    name        VARCHAR(200)                NOT NULL,
    target_date DATE                        NOT NULL,
    source      VARCHAR(20)                 NOT NULL,
    created_by  BIGINT                      NOT NULL,
    version     BIGINT                      NOT NULL DEFAULT 0,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_milestones_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_milestones_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_milestones_source CHECK (source IN ('MANUAL', 'AI_DRAFT'))
);

CREATE INDEX idx_milestones_project_id ON milestones (project_id);

CREATE TABLE milestone_tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id BIGINT                      NOT NULL,
    task_id      BIGINT                      NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_milestone_tasks_milestone FOREIGN KEY (milestone_id) REFERENCES milestones (id),
    CONSTRAINT fk_milestone_tasks_task FOREIGN KEY (task_id) REFERENCES wbs_tasks (id),
    CONSTRAINT uk_milestone_tasks_milestone_id_task_id UNIQUE (milestone_id, task_id)
);
