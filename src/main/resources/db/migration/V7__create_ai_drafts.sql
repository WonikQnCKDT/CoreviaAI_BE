-- AI 초안·추정값 공통 저장(10. AI 리스크·AI 초안 ERD의 ai_drafts). FR-PRJ-07(WBS 초안)이 처음 쓰고,
-- FR-TSK-11·PSN-04·DOC-02·RPT-01·AIR-14·15가 같은 테이블에 feature만 달리해 쓴다.
--   AI가 만든 결과(output)와 사람의 수락·거절 결과(status, decided_by/at)를 남긴다(NFR-07 AI 요청·승인 이력, NFR-08 사람 승인).
--   PM이 승인하기 전에는 업무 테이블(wbs_tasks 등)을 바꾸지 않는다. 이 테이블은 AI 결과 기록이다.
--   사용자 입력 원문(요구사항 문서 등)은 저장하지 않는다.
-- enum 컬럼: feature·status는 값이 닫혀 있어 CHECK를 둔다(00. 개요·규칙 5절). AI 기능이 늘면 CHECK도 함께 바꾼다.
-- 보관 기간(1년, NFR-07) 정리는 FR-ADM-04에서 구현한다.
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE ai_drafts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature       VARCHAR(30)                 NOT NULL,
    project_id    BIGINT,
    target_type   VARCHAR(30),
    target_id     BIGINT,
    requested_by  BIGINT,
    status        VARCHAR(20)                 NOT NULL DEFAULT 'DRAFT',
    output        TEXT,
    model         VARCHAR(100),
    latency_ms    INT,
    decided_by    BIGINT,
    decided_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ai_drafts_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_ai_drafts_requested_by FOREIGN KEY (requested_by) REFERENCES users (id),
    CONSTRAINT fk_ai_drafts_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_ai_drafts_feature CHECK (feature IN ('WBS_DRAFT', 'TASK_DETAIL', 'WORKLOG_SUMMARY', 'MEETING_SUMMARY',
        'WEEKLY_REPORT', 'PROGRESS_ESTIMATE', 'EFFORT_ESTIMATE')),
    CONSTRAINT ck_ai_drafts_status CHECK (status IN ('DRAFT', 'ACCEPTED', 'PARTIALLY_ACCEPTED', 'REJECTED', 'FAILED'))
);

CREATE INDEX idx_ai_drafts_feature_target ON ai_drafts (feature, target_type, target_id);
CREATE INDEX idx_ai_drafts_created_at ON ai_drafts (created_at);
