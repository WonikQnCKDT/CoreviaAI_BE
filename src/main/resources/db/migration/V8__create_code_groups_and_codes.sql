-- FR-ADM-07 공통 코드 관리(02. 관리 ERD의 code_groups·codes)
--   code_groups : 코드 그룹(위험 수준·업무 진행 상태·요청 처리 결과·프로젝트 상태). 그룹은 이 마이그레이션처럼 개발자가 추가한다(관리 API 없음)
--   codes       : 그룹별 코드 값. 코드 값(code)과 라벨 키(label_key)는 고정이며 수정·삭제하지 않는다.
--                 관리자는 코드 추가와 정렬 순서·사용 여부(active)만 바꾼다. 표시 텍스트는 i18n_labels(FR-ADM-06, V9)에서 label_key로 관리한다.
-- label_key 규칙: 그룹 = 'codeGroup.<group_code>', 코드 = 'code.<group_code>.<code>' (서버가 만들며 요청으로 받지 않는다)
-- 코드 enum과 같은 그룹(TASK_STATUS = WbsTaskStatus, PROJECT_STATUS = ProjectStatus)은 시드가 enum 값과 같아야 한다(통합 테스트로 검증).
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE code_groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code VARCHAR(50)                 NOT NULL,
    label_key  VARCHAR(100)                NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_code_groups_group_code UNIQUE (group_code)
);

CREATE TABLE codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id   BIGINT                      NOT NULL,
    code       VARCHAR(50)                 NOT NULL,
    label_key  VARCHAR(100)                NOT NULL,
    sort_order INT                         NOT NULL,
    active     BOOLEAN                     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_codes_group FOREIGN KEY (group_id) REFERENCES code_groups (id),
    -- 그룹별 조회(group_id 선두)에도 이 인덱스를 쓴다.
    CONSTRAINT uk_codes_group_id_code UNIQUE (group_id, code),
    CONSTRAINT ck_codes_sort_order CHECK (sort_order >= 0)
);

INSERT INTO code_groups (group_code, label_key, created_at, updated_at) VALUES
    ('RISK_LEVEL', 'codeGroup.RISK_LEVEL', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('TASK_STATUS', 'codeGroup.TASK_STATUS', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('REQUEST_RESULT', 'codeGroup.REQUEST_RESULT', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
    ('PROJECT_STATUS', 'codeGroup.PROJECT_STATUS', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

-- 위험 수준: 정상·주의·위험 (FR-ADM-07)
INSERT INTO codes (group_id, code, label_key, sort_order, active, created_at, updated_at)
SELECT g.id, v.code, 'code.RISK_LEVEL.' || v.code, v.sort_order, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM code_groups g
CROSS JOIN (VALUES ('NORMAL', 1), ('CAUTION', 2), ('DANGER', 3)) AS v (code, sort_order)
WHERE g.group_code = 'RISK_LEVEL';

-- 업무 진행 상태: WbsTaskStatus와 같은 값·순서(칸반 기본 컬럼 대기·진행·검토·완료, FR-TSK-02)
INSERT INTO codes (group_id, code, label_key, sort_order, active, created_at, updated_at)
SELECT g.id, v.code, 'code.TASK_STATUS.' || v.code, v.sort_order, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM code_groups g
CROSS JOIN (VALUES ('TODO', 1), ('IN_PROGRESS', 2), ('REVIEW', 3), ('DONE', 4)) AS v (code, sort_order)
WHERE g.group_code = 'TASK_STATUS';

-- 요청 처리 결과: 명세는 'SUCCESS 등'만 정하므로 SUCCESS·FAILURE로 시작한다(필요한 값은 관리 API로 추가)
INSERT INTO codes (group_id, code, label_key, sort_order, active, created_at, updated_at)
SELECT g.id, v.code, 'code.REQUEST_RESULT.' || v.code, v.sort_order, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM code_groups g
CROSS JOIN (VALUES ('SUCCESS', 1), ('FAILURE', 2)) AS v (code, sort_order)
WHERE g.group_code = 'REQUEST_RESULT';

-- 프로젝트 상태: ProjectStatus와 같은 값·순서
INSERT INTO codes (group_id, code, label_key, sort_order, active, created_at, updated_at)
SELECT g.id, v.code, 'code.PROJECT_STATUS.' || v.code, v.sort_order, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM code_groups g
CROSS JOIN (VALUES ('PLANNED', 1), ('IN_PROGRESS', 2), ('ON_HOLD', 3), ('COMPLETED', 4), ('CANCELLED', 5)) AS v (code, sort_order)
WHERE g.group_code = 'PROJECT_STATUS';
