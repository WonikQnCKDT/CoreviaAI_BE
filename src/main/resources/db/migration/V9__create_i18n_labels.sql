-- FR-ADM-06 다국어 라벨 관리(02. 관리 ERD의 i18n_labels)
--   i18n_labels : 라벨 키별 언어 컬럼(한국어 필수, 영어·번체 중국어 선택). 번역이 없으면(NULL) 화면은 한국어로 표시한다.
--                 화면 코드는 label_key만 쓰고, 문구는 관리자가 API로 등록·수정한다(재배포 없음). 문구 변경 이력은 audit_logs.
--   빈 문자열은 저장하지 않는다(서비스가 NULL로 바꾼다). 그래야 '번역 누락 = NULL' 하나로 필터한다.
-- 시드: V8 공통 코드의 라벨 키 전부(그룹 4개 'codeGroup.<GROUP>', 코드 14개 'code.<GROUP>.<CODE>'). 통합 테스트가 코드 라벨 키와 1:1인지 검증한다.
-- 기존 데이터 영향: 새 테이블만 만든다. 기존 테이블 변경 없음.
-- 되돌릴 때는 테이블을 지우는 새 버전을 추가한다(roll-forward).

CREATE TABLE i18n_labels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label_key  VARCHAR(100)                NOT NULL,
    text_ko    VARCHAR(500)                NOT NULL,
    text_en    VARCHAR(500),
    text_zh_tw VARCHAR(500),
    version    BIGINT                      NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_i18n_labels_label_key UNIQUE (label_key),
    CONSTRAINT ck_i18n_labels_text_ko_not_blank CHECK (TRIM(text_ko) <> '')
);

